"""macOS Seatbelt backend for the bash-child enforcement layer.

This mirrors :mod:`tau_coding._landlock` for Apple platforms: the approval
module's ``PathJail`` plus the shared ``EnforcePolicy`` struct are compiled
into a Seatbelt (SBPL) sandbox profile that ``sandbox-exec`` applies at
child spawn time. The confinement therefore covers every descendant of
every bash call, before any user code runs — the wall is the kernel's,
the same property the Landlock exec-bridge provides on Linux.

Deliberate semantic divergences from Linux (documented in the guide):

- Reads follow macOS reality: sandbox-exec profiles need dynamic-linker
  access to ``/System`` and similar wide system trees, so file reads are
  granted broadly *except* an explicit deny on ``$HOME`` credential
  locations (``~/.ssh``, ``~/.aws``, ``~/.tau`` relay tokens, keychains,
  gcloud, netrc). The Linux ruleset instead reads only system paths.
- Writes and outbound network are enforced exactly like Landlock:
  write is jailed (jail + ``/tmp`` + ``/dev`` only); network is denied
  unless the policy allows named TCP/UDP ports.

``sandbox-exec`` is deprecated by Apple (a banner is printed to stderr on
every invocation); the banner is an exact two-line constant that the bash
tool strips under enforcement so transcripts stay clean. Profiles are
cached per content hash under the process temp directory.
"""

from __future__ import annotations

import hashlib
import os
import sys
import tempfile
from pathlib import Path

from tau_coding._landlock import EnforcePolicy
from tau_coding.tool_approval import PathJail

SANDBOX_EXEC = "/usr/bin/sandbox-exec"

# Apple's deprecation notice, byte-exact (appears on stderr of every
# sandbox-exec invocation; stripped from tool output so it doesn't
# pollute transcripts).
SANDBOX_EXEC_BANNER_LINES: tuple[str, ...] = (
    "WARNING: sandbox-exec is deprecated.",
    "Consider adopting the App Sandbox instead.",
)

# HOME sub-trees denied to readers even though read is otherwise broad on
# macOS. The relay/provider token store and the usual credential dirs.
_HOME_READ_DENIES: tuple[str, ...] = (
    ".ssh",
    ".aws",
    ".config/gcloud",
    ".netrc",
    ".tau",
    "Library/Keychains",
)


def seatbelt_available() -> bool:
    """True on macOS with the OS ``sandbox-exec`` helper present."""
    if sys.platform != "darwin":
        return False
    return os.path.exists(SANDBOX_EXEC)


def _sb_quote(path: Path | str) -> str:
    """Quote a path for SBPL: always-quoted, with minimal escaping."""
    text = str(path).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def _interpreter_prefix(python_path: str | None) -> str | None:
    """Grant scope for the interpreter that will exec child commands.

    ``sys.executable`` on a uv tool install is
    ``~/.local/share/uv/tools/<name>/bin/python``; its tool prefix (two
    levels up) covers the real interpreter plus its site-packages.
    """
    if not python_path:
        return None
    exe_dir = Path(python_path).resolve().parent
    if exe_dir.name == "bin" and exe_dir.parent.name not in ("usr", "bin", "sbin"):
        return str(exe_dir.parent)
    return None


def build_seatbelt_profile(
    jail: PathJail,
    *,
    policy: EnforcePolicy | None = None,
    python_path: str | None = None,
) -> str:
    """Compile the jail + policy into an SBPL profile string.

    Rules are order-sensitive: Seatbelt evaluates later rules over earlier
    ones, so the shape is deny-all, broad system allows, the HOME
    read-deny boundary, then the overrides (jail, tmp/dev, interpreter,
    cwd) which win.
    """
    effective = policy or EnforcePolicy()
    lines: list[str] = [
        "(version 1)",
        "; Generated by tau: approval gate kernel layer (seatbelt backend).",
        "(deny default)",
        "; process",
        "(allow process-exec*)",
        "(allow process-fork)",
        "(allow signal (target self))",
        "; system reads (dynamic linker, CLI basics)",
        "(allow sysctl-read)",
        (
            "(allow file-read* "
            + " ".join(
                f"(subpath {_sb_quote(target)})"
                for target in (
                    "/usr",
                    "/bin",
                    "/sbin",
                    "/System",
                    "/Library",
                    "/opt",
                    "/etc",
                    "/private/etc",
                    "/dev",
                )
            )
            + ")"
        ),
        (
            "(allow file-read* "
            + " ".join(
                f"(subpath {_sb_quote(target)})"
                for target in (
                    "/private/var/db/timezone",
                    "/private/var/db/locale",
                )
            )
            + ")"
        ),
    ]
    if effective.network == "allow":
        ports = effective.network_connect_ports or (443,)
        for port in ports:
            lines.append(f"(allow network-outbound (remote tcp-* :{port}))")
        lines.extend(
            [
                "(allow network-outbound (remote udp-* :53))",
                "(allow system-socket)",
                "(allow network-outbound (remote tcp-* :53))",
                # DNS answers reach the process through mDNSResponder.
                "(allow mach-lookup)",
                "(allow mach-register)",
            ]
        )
    # HOME boundary: reads denied so secrets (ssh keys, cloud creds, tau's
    # own token store) are not readable even in the wide-read tier.
    lines.append("; HOME credential boundary")
    lines.append(f"(deny file-read* (subpath {_sb_quote(Path.home())}))")
    for relative in _HOME_READ_DENIES:
        lines.append(f"(deny file-read* (subpath {_sb_quote(Path.home() / relative)}))")
    # Overrides (they win over the denials above).
    lines.append("; overrides")
    interpreter = _interpreter_prefix(python_path)
    if interpreter:
        lines.extend(
            [
                f"(allow file-read* (subpath {_sb_quote(interpreter)}))",
                f"(allow file-write* (subpath {_sb_quote(interpreter)}))",
            ]
        )
    for root in jail.paths:
        lines.append(f"(allow file-read* (subpath {_sb_quote(root.expanduser())}))")
        lines.append(f"(allow file-write* (subpath {_sb_quote(root.expanduser())}))")
    for target in ("/tmp", "/private/tmp", "/dev"):
        lines.append(f"(allow file-write* (subpath {_sb_quote(target)}))")
    if effective.include_cwd_read:
        lines.append(f"(allow file-read* (subpath {_sb_quote(Path.cwd())}))")
    return "\n".join(lines) + "\n"


def launcher_command(
    jail: PathJail,
    *,
    policy: EnforcePolicy | None = None,
    python_path: str | None = None,
) -> list[str] | None:
    """Return the argv prefix confining a bash child on macOS, or None.

    ``None`` means enforcement is unavailable (not macOS, no
    ``/usr/bin/sandbox-exec``); callers degrade to approval-only. Callers
    append ``bash -c <command>``; ``sandbox-exec`` applies the generated
    profile before the child's first instruction.
    """
    if not seatbelt_available():
        return None
    profile = build_seatbelt_profile(jail, policy=policy, python_path=python_path)
    destination = _cached_profile_path(profile)
    if not destination.exists():
        try:
            with open(destination, "x", encoding="utf-8") as handle:
                handle.write(profile)
            os.chmod(destination, 0o600)
        except FileExistsError:
            # Another process (or a stale cache) already wrote this
            # hash-identical profile; reuse it as-is.
            pass
    return [SANDBOX_EXEC, "-f", str(destination)]


def strip_sandbox_exec_banner(output: str) -> str:
    """Drop Apple's exact deprecation banner lines from tool output."""
    keep = [line for line in output.splitlines() if line.rstrip() not in SANDBOX_EXEC_BANNER_LINES]
    if len(keep) == len(output.splitlines()):
        return output
    return "\n".join(keep)


def _cached_profile_path(profile: str) -> Path:
    digest = hashlib.sha256(profile.encode("utf-8")).hexdigest()[:16]
    return Path(tempfile.gettempdir()) / f"tau-seatbelt-{digest}.sb"
